@router.post("/predict", response_model=DiagnosisResponse)
async def analyze_plant_leaf(file: UploadFile = File(...)) -> DiagnosisResponse:
    """Upload an image of a plant leaf to detect and diagnose diseases."""
    # 1. Validate content type
    allowed_types = ["image/jpeg", "image/png", "image/webp", "image/jpg"]
    if file.content_type not in allowed_types:
        raise HTTPException(
            status_code=status.HTTP_415_UNSUPPORTED_MEDIA_TYPE,
            detail=f"Unsupported image type: '{file.content_type}'. Allowed types: {allowed_types}",
        )

    try:
        # 2. Read bytes
        image_bytes = await file.read()
        if len(image_bytes) == 0:
            raise HTTPException(status_code=400, detail="Uploaded file is empty.")
        if len(image_bytes) > 10 * 1024 * 1024:
            raise HTTPException(status_code=413, detail="Image exceeds 10MB file limit.")

        # 3. Preprocess and run inference
        tensor = preprocessor.load_and_preprocess(image_bytes)
        result = engine.predict(tensor)

        prediction_id = f"diag_{uuid.uuid4().hex[:10]}"
        return DiagnosisResponse(
            prediction_id=prediction_id,
            predicted_class=result["predicted_class"],
            confidence=result["confidence"],
            is_reliable=result["is_reliable"],
            status=result["status"],
            treatment_recommendation=result["treatment_recommendation"],
            all_class_probabilities=result["all_class_probabilities"],
        )

    except ValueError as val_err:
        raise HTTPException(status_code=400, detail=str(val_err)) from val_err
    except Exception as exc:
        logger.error("Failed to diagnose plant leaf: %s", exc, exc_info=True)
        raise HTTPException(
            status_code=status.HTTP_500_INTERNAL_SERVER_ERROR,
            detail=f"Prediction pipeline failure: {exc}",
        ) from exc
