from __future__ import annotations

import logging
from pathlib import Path
from typing import Tuple, Optional
import numpy as np
from PIL import Image

logger = logging.getLogger("custom-d7er.preprocessing")


class ImagePreprocessor:
    """Standardizes, normalizes, and augments images for model ingestion."""

    def __init__(
        self,
        target_size: Tuple[int, int] = (224, 224),
        mean: Tuple[float, float, float] = (0.485, 0.456, 0.406),
        std: Tuple[float, float, float] = (0.229, 0.224, 0.225),
    ) -> None:
        self.target_size = target_size
        self.mean = np.array(mean, dtype=np.float32)
        self.std = np.array(std, dtype=np.float32)

    def load_and_preprocess(self, image_input: bytes | str | Path) -> np.ndarray:
        """Load image from raw bytes or file path, resize, and apply standard normalization."""
        try:
            if isinstance(image_input, (str, Path)):
                image = Image.open(image_input).convert("RGB")
            elif isinstance(image_input, bytes):
                import io
                image = Image.open(io.BytesIO(image_input)).convert("RGB")
            else:
                raise ValueError("Unsupported image input type")

            # Resize using high-quality anti-aliasing filter
            image = image.resize(self.target_size, Image.Resampling.BILINEAR)
            arr = np.array(image, dtype=np.float32) / 255.0

            # Normalize with ImageNet channel statistics
            normalized = (arr - self.mean) / self.std

            # Transpose to channel-first format (C, H, W) for PyTorch / ONNX models
            tensor = np.transpose(normalized, (2, 0, 1))
            # Add batch dimension (1, C, H, W)
            return np.expand_dims(tensor, axis=0)

        except Exception as exc:
            logger.error("Preprocessing failed for image: %s", exc)
            raise ValueError(f"Image preprocessing error: {exc}") from exc

    def augment(self, image_array: np.ndarray) -> np.ndarray:
        """Apply light data augmentations (horizontal flip, subtle brightness adjustments)."""
        augmented = image_array.copy()
        if np.random.rand() > 0.5:
            augmented = np.flip(augmented, axis=-1)  # horizontal flip
        return augmented
